// Arunika — Sky Courier of the Archipelago.
// main.ts — the entrypoint. It hands the game in: it copies game/ and
// screenshots/ from this repository to /output (or MAKEFUN_OUTPUT_DIR
// outside the grader) and writes /output/dossier.json with buildDossier
// from vendor/makefun-game.ts, exactly as the kit's starter does.
// The program is deterministic: the same repository always writes the
// same bytes, so the grader's two runs agree byte for byte.
import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-game.ts';

const here = dirname(fileURLToPath(import.meta.url));
const out = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(out, { recursive: true });
cpSync(join(here, 'game'), join(out, 'game'), { recursive: true });
mkdirSync(join(out, 'screenshots'), { recursive: true });
if (existsSync(join(here, 'screenshots'))) {
  cpSync(join(here, 'screenshots'), join(out, 'screenshots'), { recursive: true });
}

writeFileSync(
  join(out, 'dossier.json'),
  buildDossier(out, {
    text_max_bytes: 163840,
    screenshots: { max: 4, max_bytes: 262144 },
    game_max_files: 993,
    game_max_bytes: 50331648,
    game_path_max_bytes: 1000,
  }),
);
